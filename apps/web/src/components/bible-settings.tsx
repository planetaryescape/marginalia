"use client";
import { api } from "@marginalia/backend/convex/_generated/api";
import { useMutation, useQuery } from "convex/react";
import { useState } from "react";
import { toast } from "sonner";

export function BibleSettings() {
  const preferences = useQuery(api.bible.preferences, {});
  const setPreferences = useMutation(api.bible.setPreferences);
  const translations = useQuery(
    api.bible.translations,
    preferences?.enabled ? {} : "skip",
  );
  const [busy, setBusy] = useState(false);
  return (
    <section className="account-section" aria-labelledby="bible-settings-title">
      <h2 id="bible-settings-title" className="font-serif text-2xl">
        Bible reading
      </h2>
      <p
        id="bible-settings-description"
        className="my-3 text-sm text-[var(--reader-muted)]"
      >
        Optional. Find passages by topic or reading time, then read with your
        own notes and AI marginalia generated when you open a passage.
      </p>
      <label className="flex min-h-11 items-center gap-3 text-sm">
        <input
          type="checkbox"
          role="switch"
          aria-checked={preferences?.enabled ?? false}
          aria-describedby="bible-settings-description"
          checked={preferences?.enabled ?? false}
          disabled={!preferences || busy}
          onChange={async (event) => {
            setBusy(true);
            try {
              await setPreferences({ enabled: event.target.checked });
            } catch {
              toast.error("Couldn't change Bible reading. Please try again.");
            } finally {
              setBusy(false);
            }
          }}
        />
        Enable Bible reading
      </label>
      {preferences?.enabled && (
        <div className="mt-4 space-y-4">
          <label className="block text-sm">
            Default translation
            <select
              className="app-input mt-2 max-w-md"
              value={preferences.translation}
              disabled={busy || !translations}
              onChange={async (event) => {
                setBusy(true);
                try {
                  await setPreferences({ translation: event.target.value });
                } catch {
                  toast.error(
                    "Couldn't change the translation. Please try again.",
                  );
                } finally {
                  setBusy(false);
                }
              }}
            >
              {(
                translations ?? [
                  {
                    code: "web",
                    name: "World English Bible",
                    style: "Literal",
                    available: true,
                  },
                ]
              ).map((translation) => (
                <option
                  key={translation.code}
                  value={translation.code}
                  disabled={!translation.available}
                >
                  {translation.code.toUpperCase()} · {translation.name} ·{" "}
                  {translation.style}
                  {translation.available ? "" : " — not yet licensed"}
                </option>
              ))}
            </select>
          </label>
          <p className="max-w-xl text-sm text-[var(--reader-muted)]">
            The World English Bible is public domain. ESV and NASB (literal),
            NIV (balanced), NLT (thought-for-thought), and The Message
            (paraphrase) need suitable publisher permissions before they can be
            offered with AI marginalia.
          </p>
          <p className="text-sm text-[var(--reader-muted)]">
            Turning this off removes Bible discovery and access without deleting
            your saved passages or notes. AI features use your connected
            provider; Scripture text is never generated by AI.
          </p>
        </div>
      )}
    </section>
  );
}
